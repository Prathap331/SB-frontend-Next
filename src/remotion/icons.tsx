/** Lucide SVG for Remotion + timeline preview. Pixel size + stroke so scale() cannot hide it. */
export function LucideIconView({
  name,
  size = 64,
  color = 'white',
}: {
  name?: string;
  size?: number;
  color?: string;
}) {
  if (!name?.trim()) return null;
  const key = name.trim().toLowerCase().replace(/[\s_-]+/g, '');
  const paths = INLINE_PATHS[key];
  const svgStyle = {
    display: 'block',
    width: size,
    height: size,
    minWidth: size,
    minHeight: size,
    flexShrink: 0,
    overflow: 'visible' as const,
    color,
  };
  if (paths) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke={color}
        strokeWidth={2.75}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        style={svgStyle}
      >
        {key === 'users' ? <circle cx="9" cy="7" r="4" /> : null}
        {paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  }
  const Cmp = resolveLucideIcon(name);
  return (
    <Cmp
      size={size}
      color={color}
      strokeWidth={2.5}
      fill="none"
      style={svgStyle}
    />
  );
}
